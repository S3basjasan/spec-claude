/** Diferencia con signo: «+1», «−1» (signo menos tipográfico) o «0». */
export function formatearDiferencia(diferencia: number): string {
  if (diferencia === 0) return '0'
  const abs = Number.isInteger(diferencia) ? String(Math.abs(diferencia)) : Math.abs(diferencia).toFixed(1)
  return diferencia > 0 ? `+${abs}` : `−${abs}`
}

/** «Exp. / Conoc. / Comp.» (mismo orden del tablero). */
export function textoDePorcentajes(c: Record<'Experiencia' | 'Conocimiento' | 'Competencia', number | null>): string {
  return [c.Experiencia, c.Conocimiento, c.Competencia].map((v) => formatearPorcentaje(v)).join(' / ')
}

/** Cumplimiento 0..1 como porcentaje entero, o «—» si la dimensión no se evaluó. */
export function formatearPorcentaje(valor: number | null | undefined): string {
  return valor === null || valor === undefined ? '—' : `${Math.round(valor * 100)} %`
}
